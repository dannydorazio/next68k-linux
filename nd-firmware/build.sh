#!/bin/sh
# Assemble the NeXTdimension's i860 firmware (ndfw.s) with binutils 2.30
# for i860, the last with that target, from the next68k-i860 Docker volume
# (see README.md), and write it as a C header for the kernel driver:
# drivers/gpu/drm/tiny/nextdimension_fw.h.
#
# usage: build.sh [LINUX]   (default ../linux)
set -e

here=$(cd "$(dirname "$0")" && pwd)
linux=${1:-$(cd "$here/../../linux" && pwd)}
out=$linux/drivers/gpu/drm/tiny/nextdimension_fw.h

docker run --rm -v "$here":/w -v next68k-i860:/opt/i860:ro next68k-build sh -ec '
	cd /tmp
	/opt/i860/bin/i860-stardent-elf-as -mintel-syntax -o ndfw.o /w/ndfw.s
	/opt/i860/bin/i860-stardent-elf-ld -Ttext 0xf8000000 -e _start \
		-o ndfw.elf ndfw.o
	/opt/i860/bin/i860-stardent-elf-objcopy -O binary ndfw.elf ndfw.bin
	cat ndfw.bin' > "$here/ndfw.bin"

python3 - "$here/ndfw.bin" "$out" <<'PY'
import struct, sys
code = open(sys.argv[1], "rb").read()
code += bytes(-len(code) % 8)
words = struct.unpack("<%dI" % (len(code) // 4), code)
with open(sys.argv[2], "w") as f:
    f.write("/* SPDX-License-Identifier: GPL-2.0-only */\n")
    f.write("/*\n * i860 code for the NeXTdimension, generated by nd-firmware/build.sh\n")
    f.write(" * from nd-firmware/ndfw.s in the next68k-linux tree: instruction words,\n")
    f.write(" * to be stored at their address XOR 4 (the i860 fetches them\n")
    f.write(" * little-endian).\n */\n\n")
    f.write("static const u32 nextdim_fw[] = {\n")
    for i in range(0, len(words), 4):
        f.write("\t" + " ".join("0x%08x," % w for w in words[i:i + 4]) + "\n")
    f.write("};\n")
print("%s: %d words" % (sys.argv[2], len(words)))
PY
